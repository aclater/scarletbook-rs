/*
 * scarletbook: a clean-room reader for Super Audio CD (Scarletbook) disc images.
 *
 * Conventions, for every function:
 *
 * - Status. Calls return an SbStatus, an int32_t holding one of the SB_STATUS_*
 *   values (functions returning other types say so). On
 *   failure, sb_last_error_message() describes the error. The message belongs to the
 *   calling thread and stays valid until that thread's next call into this library.
 *
 * - Handles. SbDisc, SbTrackAudio, SbRawFrames, SbPool, SbSeekIndex, SbCancel and
 *   SbProgress are opaque. Each is created by one
 *   function and released by exactly one call to its _free function; passing NULL to a
 *   _free function does nothing. A function that creates a handle sets *out to NULL when it fails, so
 *   freeing that pointer afterwards is safe.
 *
 * - Pointers. Pointer arguments must be NULL or valid for the access the function
 *   documents. NULL where a value is required gives SB_STATUS_INVALID_ARGUMENT.
 *   Enumerations passed in (slots, string fields) are plain integers and are validated.
 *
 * - Strings are copied out as UTF-8 with a terminating NUL. len must not be NULL.
 *   *len receives the string's length without the NUL (0 when the string is absent).
 *   If the string is absent the call returns SB_STATUS_ABSENT and writes nothing to buf.
 *   If buf is NULL or cap <= *len, nothing is written to buf and the call returns
 *   SB_STATUS_BUFFER_TOO_SMALL: call again with cap > *len. A string can contain U+0000
 *   (a language code can), so use *len rather than strlen.
 *
 * - Threads. A handle may be moved between threads, but must not be used by two threads
 *   at once; an SbPool, which only holds threads, may, and so may an SbCancel and an
 *   SbProgress, made to be used from another thread while the disc or handle they come
 *   from reads (sb_disc_cancel_token, sb_track_audio_progress). To read one image on several
 *   threads at once, give each thread a clone of its disc (sb_disc_clone): a handle of
 *   its own over the same image. Read and seek callbacks
 *   (sb_disc_open_callbacks) and positional read callbacks (sb_disc_open_callbacks_at)
 *   run on the thread that makes the call that needs them, also when a pool decodes; a
 *   positional one therefore runs on several threads at once when clones of its disc
 *   are used on several threads. A log callback (sb_disc_set_log) also runs there and on the
 *   threads of the pools decoding for the disc's track handles (sb_track_audio_set_pool;
 *   in a library built with the parallel feature, rayon's global pool by default). The
 *   library has no other threads, and no global state besides the per-thread error
 *   message, two atomic counters that number the discs and images opened (so that a
 *   handle can tell the disc and image it belongs to; a clone keeps its original's
 *   numbers), and, on each pool thread, a DST
 *   decoder reused from frame to frame (a cache, not shared between threads).
 *
 * - Callbacks and re-entrancy. While a disc's callback runs, that disc and its track
 *   and raw frames handles are in use: calling into this library with them from the
 *   callback returns SB_STATUS_INVALID_ARGUMENT, and their _free functions do
 *   nothing; so is a seek index the call uses (sb_seek_index_extend, the _indexed
 *   functions). Other handles may be used. (A log callback invoked by a call that only
 *   reads the disc, such as sb_track_check, may read it too; one running on a pool
 *   thread must not use the disc or its track or raw frames handles at all, with any
 *   call, sb_track_audio_set_pool and the _free functions included.)
 *
 * - Types. Every integer is fixed-width (<stdint.h>) except size_t, used only for the
 *   lengths of caller buffers (and of the strings and data copied into them). Flags are
 *   uint8_t, 1 or 0. No enumeration type is passed by value or stored in a struct:
 *   SbStatus is int32_t, and the other enumerations (SbSlot, SbFrameStatus, ...) only
 *   name the values of uint32_t arguments and fields. In C23 and C++ they are
 *   enumerations with those fixed underlying types. There are no variadic functions.
 *   Callbacks use the C calling convention of the platform.
 *
 * - Layouts. Structs have the platform C compiler's natural alignment, with no packing
 *   pragmas, and no padding: fields are ordered so that each sits at its natural
 *   alignment, and reserved fields (written as 0) fill the rest. Each struct states its
 *   size and offsets, which the library's tests check; they are the same on every
 *   target, except that SbWarning ends with a pointer (4 bytes on a 32-bit target).
 *
 * - Panics. No panic crosses the boundary: an internal error returns SB_STATUS_PANIC.
 *   The handles involved should then be freed and not used further. If the library is
 *   built with panic=abort, the process aborts instead.
 */

